/** A function's arguments for the hint, with the one at `argument` marked; null when unknown. */
export function signatureOf(name: string, argument: number) {
  const args = SIGNATURES[name];
  if (!args) return null;
  const repeats = args.at(-1) === "…";
  // Past the listed arguments of a repeating one, the hint marks the last before "…".
  const current = repeats && argument >= args.length - 1 ? args.length - 2 : argument;
  return { name, args, current };
}

/** Whether a function is one people type often, which completion offers first. */
export const isCommon = (name: string) => name in SIGNATURES;
